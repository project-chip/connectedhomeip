void SpeakerAudioCoordinator::SetClusters(LevelControlCluster & levelControlCluster, AudioControlCluster & audioControlCluster)
{
    mLevelControlCluster = &levelControlCluster;
    mAudioControlCluster = &audioControlCluster;
}

void SpeakerAudioCoordinator::OnOffStartup(bool on)
{
    // Startup ordering between OnOffCluster and AudioControlCluster is not guaranteed, and both
    // clusters resolve their own persisted state independently, so no force-reconciliation is
    // attempted here. AudioControlCluster::OnStartup (below) is what notifies hardware of the
    // resolved initial state.
}

void SpeakerAudioCoordinator::OnOnOffChanged(bool on)
{
    // Absorb the echo generated by HandleVolumeAndMuteChange's own OnOff::SetOnOff() call.
    VerifyOrReturn(!mApplyingAudioControlChange);

    LogErrorOnFailure(mAudioControlCluster->SetSoftMuted(!on));
    Status status = mHardwareDelegate.HandleVolumeAndMuteChange(mAudioControlCluster->GetVolume(), !on);
    if (status != Status::Success)
    {
        // OnOffDelegate::OnOnOffChanged has no veto path -- OnOff is already committed by the
        // time this fires, so a hardware rejection here can only be logged, not rolled back.
        ChipLogError(AppServer, "SpeakerAudioCoordinator: hardware rejected OnOff-driven mute sync (status %d)",
                     static_cast<int>(status));
    }
}

void SpeakerAudioCoordinator::OnLevelChanged(uint8_t value)
{
    if (!mSeenFirstLevelChange)
    {
        mSeenFirstLevelChange = true;
        // This is LevelControlCluster::Startup()'s own resolved-initial-state echo, not a genuine
        // runtime Level change (see mSeenFirstLevelChange's declaration) -- consumed here
        // regardless of mApplyingAudioControlChange, so a later genuine change can never be
        // mistaken for this one. AudioControlCluster's own Startup has already resolved Volume
        // from its persisted/StartUp* state by the time this fires, so that Volume -- not this
        // Level -- is authoritative here. Only push it into LevelControl when the two actually
        // disagree (e.g. StartUpVolume overrode the persisted Volume but CurrentLevel still
        // reflects the old one): when they already agree, this avoids round-tripping CurrentLevel
        // through a Volume it didn't come from, which would otherwise drift it by rounding error
        // on every single boot.
        VerifyOrReturn(!mApplyingAudioControlChange);
        const uint16_t resolvedVolume = mAudioControlCluster->GetVolume();
        if (ScaleLevelToVolume(value) != resolvedVolume)
        {
            mApplyingAudioControlChange = true;
            LogErrorOnFailure(mLevelControlCluster->ForceCurrentLevel(ScaleVolumeToLevel(resolvedVolume)));
            mApplyingAudioControlChange = false;
        }
        return;
    }

    // Absorb the echo generated by HandleVolumeAndMuteChange's own LevelControl::SetCurrentLevel()
    // call -- including the reentrant call the ForceCurrentLevel() above triggers, since
    // mSeenFirstLevelChange is already true by the time that fires.
    VerifyOrReturn(!mApplyingAudioControlChange);

    uint16_t volume = ScaleLevelToVolume(value);
    LogErrorOnFailure(mAudioControlCluster->SetVolume(volume));
    Status status = mHardwareDelegate.HandleVolumeAndMuteChange(volume, mAudioControlCluster->GetSoftMuted());
    if (status != Status::Success)
    {
        // LevelControlDelegate::OnLevelChanged has no veto path -- CurrentLevel is already
        // committed by the time this fires, so a hardware rejection here can only be logged.
        ChipLogError(AppServer, "SpeakerAudioCoordinator: hardware rejected LevelControl-driven volume sync (status %d)",
                     static_cast<int>(status));
    }
}

void SpeakerAudioCoordinator::OnStartup(const StartupState & state)
{
    mHardwareDelegate.OnStartup(state);
}

Status SpeakerAudioCoordinator::HandleBassChanged(int16_t bass)
{
    return mHardwareDelegate.HandleBassChanged(bass);
}

Status SpeakerAudioCoordinator::HandleMidChanged(int16_t mid)
{
    return mHardwareDelegate.HandleMidChanged(mid);
}

Status SpeakerAudioCoordinator::HandleTrebleChanged(int16_t treble)
{
    return mHardwareDelegate.HandleTrebleChanged(treble);
}

Status SpeakerAudioCoordinator::HandleVolumeAndMuteChange(uint16_t newVolume, bool newSoftMuted)
{
    Status status = mHardwareDelegate.HandleVolumeAndMuteChange(newVolume, newSoftMuted);
    VerifyOrReturnValue(status == Status::Success, status);

    // Called before AudioControlCluster's own command handler commits newVolume/newSoftMuted, so
    // this is still the pre-change Volume.
    SyncLevelControlToAudioState(mAudioControlCluster->GetVolume(), newVolume, newSoftMuted);
    return Status::Success;
}

CHIP_ERROR SpeakerAudioCoordinator::SetVolume(uint16_t volume)
{
    const uint16_t oldVolume = mAudioControlCluster->GetVolume();
    ReturnErrorOnFailure(mAudioControlCluster->SetVolume(volume));
    SyncLevelControlToAudioState(oldVolume, volume, mAudioControlCluster->GetSoftMuted());
    return CHIP_NO_ERROR;
}

CHIP_ERROR SpeakerAudioCoordinator::SetSoftMuted(bool softMuted)
{
    // SoftMuted alone never changes Volume.
    const uint16_t volume = mAudioControlCluster->GetVolume();
    ReturnErrorOnFailure(mAudioControlCluster->SetSoftMuted(softMuted));
    SyncLevelControlToAudioState(volume, volume, softMuted);
    return CHIP_NO_ERROR;
}

CHIP_ERROR SpeakerAudioCoordinator::SetPhysicallyMuted(bool physicallyMuted)
{
    return mAudioControlCluster->SetPhysicallyMuted(physicallyMuted);
}

void SpeakerAudioCoordinator::SyncLevelControlToAudioState(uint16_t oldVolume, uint16_t newVolume, bool newSoftMuted)
{
    mApplyingAudioControlChange = true;
    if (newSoftMuted)
    {
        // Feed LevelControlCluster's own "restore on next On" memory before suppressing its
        // reactive choreography below, so a later raw On/Toggle command -- which isn't
        // suppressed and does derive its target from that memory -- restores this level
        // instead of collapsing to OnLevel/MaxLevel. Nudge a value that lands exactly on
        // MinLevel up by one: MinLevel and MinLevel+1 already round-trip to the same Volume
        // (Level's range is wider than Volume's), so this costs nothing observable while
        // sidestepping MoveToLevelCommand's On-command-to-MinLevel-collapses-to-Off rule
        // (LevelControlCluster.cpp) for that later raw On.
        DataModel::Nullable<uint8_t> currentLevel = mLevelControlCluster->GetCurrentLevel();
        if (!currentLevel.IsNull())
        {
            uint8_t levelBeforeMute = currentLevel.Value();
            uint8_t minLevel        = mLevelControlCluster->GetMinLevel();
            if (levelBeforeMute == minLevel && minLevel < mLevelControlCluster->GetMaxLevel())
            {
                levelBeforeMute++;
            }
            mLevelControlCluster->SetLevelBeforeTurnedOff(levelBeforeMute);
        }
    }
    // Goes through LevelControlCluster::ForceOnOff (not OnOffCluster::SetOnOff directly) so
    // LevelControlCluster's own On/Off-coupled level transition doesn't run for this sync: that
    // choreography derives its target level from stale internal state (the level before the last
    // mute) and, when that target happens to equal MinLevel, collapses OnOff back to false right
    // after this call -- which previously fought with the SetCurrentLevel call below. ForceOnOff
    // also stops any in-flight transition (e.g. from an OnOffTransitionTime-driven fade a raw
    // On/Off command started), so it can't keep ticking underneath this mute/unmute and re-sync
    // AudioControl.Volume away from what this call intended.
    LogErrorOnFailure(mLevelControlCluster->ForceOnOff(!newSoftMuted));
    // Only re-derive CurrentLevel when Volume is actually changing. Mute/Unmute/ToggleMuted call
    // this with newVolume == oldVolume, and Level<->Volume scaling is lossy (Level's range is
    // wider than Volume's) -- recomputing unconditionally would round-trip CurrentLevel through a
    // Volume it didn't come from, drifting it by rounding error and spuriously reporting it on
    // every mute toggle even though Volume never changed.
    if (newVolume != oldVolume)
    {
        LogErrorOnFailure(mLevelControlCluster->ForceCurrentLevel(ScaleVolumeToLevel(newVolume)));
    }
    mApplyingAudioControlChange = false;
}

uint16_t SpeakerAudioCoordinator::ScaleLevelToVolume(uint8_t level) const
{
    const uint8_t minLevel   = mLevelControlCluster->GetMinLevel();
    const uint8_t maxLevel   = mLevelControlCluster->GetMaxLevel();
    const uint16_t minVolume = mAudioControlCluster->GetMinDeviceVolume();
    const uint16_t maxVolume = std::min(mAudioControlCluster->GetMaxDeviceVolume(), mAudioControlCluster->GetMaxUserVolume());

    VerifyOrReturnValue(maxLevel > minLevel && maxVolume > minVolume, minVolume);

    const uint32_t span  = static_cast<uint32_t>(level - minLevel) * (maxVolume - minVolume);
    const uint32_t range = maxLevel - minLevel;
    return static_cast<uint16_t>(minVolume + (span + range / 2) / range);
}

uint8_t SpeakerAudioCoordinator::ScaleVolumeToLevel(uint16_t volume) const
{
    const uint8_t minLevel   = mLevelControlCluster->GetMinLevel();
    const uint8_t maxLevel   = mLevelControlCluster->GetMaxLevel();
    const uint16_t minVolume = mAudioControlCluster->GetMinDeviceVolume();
    const uint16_t maxVolume = std::min(mAudioControlCluster->GetMaxDeviceVolume(), mAudioControlCluster->GetMaxUserVolume());

    VerifyOrReturnValue(maxVolume > minVolume && maxLevel > minLevel, minLevel);

    const uint32_t span  = static_cast<uint32_t>(volume - minVolume) * (maxLevel - minLevel);
    const uint32_t range = maxVolume - minVolume;
    return static_cast<uint8_t>(minLevel + (span + range / 2) / range);
}


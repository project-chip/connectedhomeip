float SrgbFromLinear(float channel)
{
    return (channel <= 0.0031308f) ? (channel * 12.92f) : (1.055f * std::pow(channel, 1.0f / 2.4f) - 0.055f);
}

// CIE xy to sRGB at full brightness: out-of-gamut channels are clipped and the result is scaled so
// the brightest channel is 1, leaving brightness to Level Control.
void XYToRgb(uint16_t x, uint16_t y, float & outR, float & outG, float & outB)
{
    const float cx = static_cast<float>(x) / kXYScale;
    const float cy = static_cast<float>(y) / kXYScale;
    if (cy <= 0.0f)
    {
        outR = outG = outB = 1.0f;
        return;
    }

    const float cieX = cx / cy;
    const float cieZ = (1.0f - cx - cy) / cy;

    float r = std::max((3.2404542f * cieX) - 1.5371385f - (0.4985314f * cieZ), 0.0f);
    float g = std::max((-0.9692660f * cieX) + 1.8760108f + (0.0415560f * cieZ), 0.0f);
    float b = std::max((0.0556434f * cieX) - 0.2040259f + (1.0572252f * cieZ), 0.0f);

    const float peak = std::max({ r, g, b });
    if (peak <= 0.0f)
    {
        outR = outG = outB = 1.0f;
        return;
    }
    outR = SrgbFromLinear(r / peak);
    outG = SrgbFromLinear(g / peak);
    outB = SrgbFromLinear(b / peak);
}
